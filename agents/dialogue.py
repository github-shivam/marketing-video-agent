"""The dialogue node: the caption and hashtags that ship with the post.

Tool-free. Audio is generated by the video model from the prompt cues the
screenwriter already produced, so there is no voiceover file to make.
"""

from __future__ import annotations

from typing import Any

from config import Settings
from state import Dialogue, PostState

from .common import describe_brief, structured

DIALOGUE_SYSTEM = """You write the caption and hashtags for an Instagram Reel.

Caption:
- Open with a line that earns the tap on "more". The first 125 characters are
  all most people see.
- Write in the voice described in the brief. Under 150 words, and shorter is
  usually better.
- End with the call to action, stated plainly, if the brief has one.
- No emoji walls. No "link in bio" unless the CTA actually is a link in bio.
- Only state facts the brief supports.

Hashtags:
- Between 5 and 12, all genuinely relevant.
- Mix broad niche tags with specific long-tail ones. Avoid banned or spammy
  generic tags such as #follow4follow or #viral.
- No leading '#' needed; it is added automatically."""


def dialogue_node(settings: Settings):
    """Build the dialogue node."""

    async def run(state: PostState) -> dict[str, Any]:
        brief = state["brief"]
        screenplay = state["screenplay"]
        user = (
            f"{describe_brief(brief)}\n\n"
            f"VIDEO\nTitle: {screenplay.title}\nLogline: {screenplay.logline}\n"
            f"Hook: {screenplay.hook}\nCTA: {screenplay.cta}\n\n"
            "Write the caption and hashtags for this video."
        )
        dialogue = await structured(
            settings, "dialogue", Dialogue, DIALOGUE_SYSTEM, user
        )
        return {"dialogue": dialogue}

    return run
